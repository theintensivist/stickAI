"""Build a VLW (smooth, anti-aliased) font for M5GFX: ASCII + Arabic letters and
their joined presentation forms, from DejaVu Sans (free licence)."""
import struct, sys
from PIL import ImageFont
SIZE = int(sys.argv[1]) if len(sys.argv) > 1 else 14
font = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf', SIZE)
from fontTools.ttLib import TTFont
cmap = TTFont('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf')['cmap'].getBestCmap()
cps = list(range(0x20, 0x7F)) + [0x060C, 0x061B, 0x061F, 0x0640] + list(range(0x0621, 0x064B)) \
      + list(range(0x0660, 0x066A)) + list(range(0xFE70, 0xFEFD))
cps = sorted(c for c in set(cps) if c == 0x20 or c in cmap)
ascent, descent = font.getmetrics()
headers, bitmaps = [], b''
for cp in cps:
    ch = chr(cp)
    adv = int(round(font.getlength(ch)))
    if cp == 0x20:
        headers.append((cp, 0, 0, adv, 0, 0)); continue
    mask, (ox, oy) = font.getmask2(ch, mode='L', anchor='ls')
    w, h = mask.size
    data = bytes(mask)
    headers.append((cp, h, w, adv, -oy, ox))
    bitmaps += data
out = struct.pack('>6i', len(cps), 11, SIZE, 0, ascent, descent)
for (cp, h, w, adv, dy, dx) in headers:
    out += struct.pack('>7i', cp, h, w, adv, dy, dx, 0)
out += bitmaps
name = 'font_ar%d' % SIZE
with open(sys.argv[2], 'w') as f:
    f.write('// Smooth font: ASCII + Arabic (letters and joined forms), from DejaVu Sans %dpx.\n' % SIZE)
    f.write('// DejaVu fonts: free licence (Bitstream Vera derived). Generated by tools/make_vlw.py.\n')
    f.write('#pragma once\n#include <stdint.h>\n')
    f.write('static const uint8_t FONT_AR[%d] = {\n' % len(out))
    for i in range(0, len(out), 24):
        f.write('  ' + ','.join(str(b) for b in out[i:i+24]) + ',\n')
    f.write('};\n')
print(len(cps), 'glyphs', len(out), 'bytes', 'ascent', ascent, 'descent', descent)
